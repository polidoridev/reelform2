// Real local MP4 exports in Chromium. No account, provider calls, or paid generation.
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdtemp, mkdir, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import ffmpeg from "ffmpeg-static";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const dir = await mkdtemp(join(tmpdir(), "reelform-aura-"));
const browser = await chromium.launch({ headless: true, channel: process.env.TEST_BROWSER_CHANNEL || "chrome" });
const base = process.env.TEST_BASE_URL || "http://localhost:3012";
const errors = [], apiCalls = [];
let page;
try {
  for (let i = 0; i < 2; i++) execFileSync(ffmpeg, ["-hide_banner", "-loglevel", "error", "-f", "lavfi", "-i", i ? "color=c=blue:size=320x240:rate=30" : "testsrc2=size=240x320:rate=30", "-t", "4", "-c:v", "libx264", "-pix_fmt", "yuv420p", join(dir, `clip-${i}.mp4`)]);
  execFileSync(ffmpeg, ["-hide_banner", "-loglevel", "error", "-f", "lavfi", "-i", "sine=frequency=440:sample_rate=44100", "-t", "12", join(dir, "music.wav")]);
  page = await browser.newPage({ viewport: { width: 1440, height: 1080 }, reducedMotion: "reduce" });
  page.on("pageerror", error => errors.push(error.message));
  page.on("request", request => { if (new URL(request.url()).pathname.startsWith("/api/") && !(request.method() === "GET" && new URL(request.url()).pathname === "/api/aura/plan")) apiCalls.push(request.url()); });
  await page.goto(`${base}/aura`);
  await page.waitForLoadState("networkidle");
  await page.getByRole("button", { name: "Essential only" }).click();
  const create = page.getByRole("button", { name: "Create aura edit" });
  await create.waitFor();
  assert(await create.isDisabled());
  await page.getByLabel("Upload aura clips").setInputFiles([join(dir, "clip-0.mp4"), join(dir, "clip-1.mp4")]);
  await page.getByText("clip-1.mp4", { exact: true }).waitFor();
  await page.getByLabel("Length", { exact: true }).selectOption("8");
  await page.getByRole("button", { name: "Move clip 2 earlier" }).click();
  assert.equal(await page.locator(".aura-clips li").first().locator("strong").textContent(), "clip-1.mp4");
  await page.getByRole("button", { name: "Move clip 1 later" }).click();
  await page.getByLabel("Clip 1 start time").fill("1");
  await page.getByRole("button", { name: "Preview music" }).click();
  await page.getByRole("button", { name: "Stop preview" }).click();
  await create.click();
  console.log("Rendering portrait with included soundtrack…");
  const download = page.getByRole("link", { name: /Download your edit/ });
  await download.waitFor({ timeout: 120_000 });
  console.log("Portrait rendered.");
  const video = page.getByLabel("Finished aura edit");
  await video.evaluate(element => new Promise(resolve => { if (element.readyState >= 1) resolve(); else element.addEventListener("loadedmetadata", resolve, { once: true }); }));
  const metadata = await video.evaluate(element => ({ duration: element.duration, width: element.videoWidth, height: element.videoHeight }));
  assert(Math.abs(metadata.duration - 8) < 0.15, JSON.stringify(metadata));
  assert.equal(metadata.width, 720); assert.equal(metadata.height, 1280);
  const pendingDownload = page.waitForEvent("download"); await download.click();
  const output = join(dir, "aura.mp4"); await (await pendingDownload).saveAs(output);
  // Decode the complete export and require both a video and an audio stream.
  execFileSync(ffmpeg, ["-hide_banner", "-loglevel", "error", "-i", output, "-map", "0:v:0", "-map", "0:a:0", "-f", "null", "-"]);
  await mkdir("outputs", { recursive: true });
  await page.screenshot({ path: "outputs/aura-desktop.png", fullPage: true });
  await page.getByRole("button", { name: /^Midnight/ }).click();
  assert.equal(await download.count(), 0, "settings changes invalidate a stale export");
  await page.getByLabel("Upload aura music").setInputFiles(join(dir, "music.wav"));
  await page.getByLabel("Track tempo (BPM)").fill("120");
  await page.getByLabel("First beat / start (seconds)").fill("8");
  assert(await create.isDisabled(), "reject soundtracks shorter than the edit");
  await page.getByLabel("First beat / start (seconds)").fill("0.5");
  await page.getByLabel("Format", { exact: true }).selectOption("16:9");
  await page.getByLabel("Framing", { exact: true }).selectOption("contain");
  await create.click();
  console.log("Rendering landscape with uploaded soundtrack…");
  await download.waitFor({ timeout: 120_000 });
  await page.waitForFunction(() => document.querySelector('[aria-label="Finished aura edit"]').videoWidth === 1280);
  assert.equal(await video.evaluate(element => element.videoHeight), 720);
  await page.getByRole("button", { name: /^Clean cut/ }).click();
  await create.click();
  await page.getByRole("button", { name: "Cancel export" }).click();
  await page.getByText("Export canceled. Your clips and settings are still here.").waitFor();
  assert.equal(await page.locator(".aura-clips li").count(), 2);
  await page.getByLabel("Upload aura clips").setInputFiles({ name: "broken.mp4", mimeType: "video/mp4", buffer: Buffer.from("not a video") });
  await page.getByRole("alert").waitFor();
  assert.equal(await page.locator(".aura-clips li").count(), 2);
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "mobile must not overflow");
  await page.screenshot({ path: "outputs/aura-mobile.png", fullPage: true });
  assert.deepEqual(errors, []); assert.deepEqual(apiCalls, []);
  console.log("PASS real portrait and landscape MP4 exports, audio/video decoding, uploaded music, short-music validation, ordering, start offsets, cancellation, invalid clips, mobile layout, no provider calls.");
} catch (error) {
  if (page) { console.error((await page.locator("body").innerText()).slice(-2000)); await page.screenshot({ path: "outputs/aura-failure.png", fullPage: true }); }
  throw error;
} finally { await browser.close(); await rm(dir, { recursive: true, force: true }); }
